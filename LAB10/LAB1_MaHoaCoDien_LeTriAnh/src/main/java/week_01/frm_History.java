    private void loadHistory() {
        if (!DbConfig.isReady()) {
            lbl_status.setText("Chưa kết nối CSDL SQL Server.");
            tbl_history.setModel(HistoryDao.emptyModel());
            return;
        }
        try {
            tbl_history.setModel(HistoryDao.loadLatest(100));
            lbl_status.setText("Đã tải 100 bản ghi mới nhất.");
        } catch (Exception ex) {
            lbl_status.setText("Lỗi nạp lịch sử: " + ex.getMessage());
        }
    }

